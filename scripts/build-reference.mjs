#!/usr/bin/env node
// Regenerates docs/reference/adoption-catalog.md and docs/reference/resources.md
// from the "Adopt this" and "Resources" sections of every chapter, and the FAQ
// index (docs/06-field-guides/04-faq.md) from docs/06-field-guides/faq/*.md.
// Run from the repo root: node scripts/build-reference.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const docs = join(root, 'docs');

const parts = readdirSync(docs, { withFileTypes: true })
  .filter((d) => d.isDirectory() && /^\d\d-/.test(d.name))
  .map((d) => d.name)
  .sort();

const partTitles = {
  '01-foundations': 'Part 1: Foundations',
  '02-workspace': 'Part 2: Your workspace',
  '03-agents': 'Part 3: Building agents',
  '04-delivery': 'Part 4: Delivery with agents',
  '05-autonomy': 'Part 5: Autonomy',
  '06-field-guides': 'Part 6: Field guides',
};

function section(text, heading) {
  const lines = text.split('\n');
  const start = lines.findIndex((l) => l.trim().toLowerCase() === `## ${heading}`.toLowerCase());
  if (start === -1) return [];
  const rest = lines.slice(start + 1);
  const end = rest.findIndex((l) => /^## /.test(l));
  return end === -1 ? rest : rest.slice(0, end);
}

const chapters = [];
for (const part of parts) {
  const files = readdirSync(join(docs, part)).filter((f) => /^\d\d-.*\.md$/.test(f)).sort();
  for (const file of files) {
    const text = readFileSync(join(docs, part, file), 'utf8');
    const title = (text.match(/^# (.+)$/m) || [, file])[1].trim();
    const rows = section(text, 'Adopt this')
      .filter((l) => /^\|/.test(l.trim()))
      .slice(2) // header and separator
      .map((l) => l.trim().replace(/^\||\|$/g, '').split('|').map((c) => c.trim()))
      .filter((c) => c.length >= 5 && c[0]);
    const resources = section(text, 'Resources').filter((l) => /^\s*[-*] /.test(l)).map((l) => l.trim());
    chapters.push({ part, file, title, rows, resources });
  }
}

const note = '<!-- Generated by scripts/build-reference.mjs. Do not edit by hand. -->';

// Adoption catalogue
let cat = `${note}\n# Adoption catalogue\n\n`;
cat += '> Every practice in the playbook in one place. Each chapter ends with an "Adopt this" table; this file collects them so a reader, or a reader\'s agent, can scan all of them without opening every chapter.\n\n';
cat += '**How to read it**\n\n';
cat += '- **Applies to**: `Project` is a shared codebase, `Workspace` is one developer\'s own machine and habits, `Team` needs agreement between people.\n';
cat += '- **Effort**: `S` under an hour, `M` about a day, `L` several days or ongoing.\n';
cat += '- The parts are ordered roughly from "do this first" to "do this once the basics hold". The [transition playbook](../06-field-guides/01-ai-first-transition-playbook.md) says what must be true before each step up.\n';
cat += '- If you are an agent: do not recommend the whole list. Follow [`AGENTS.md`](../../AGENTS.md).\n\n';
const total = chapters.reduce((n, c) => n + c.rows.length, 0);
cat += `${total} practices across ${chapters.filter((c) => c.rows.length).length} chapters.\n`;
for (const part of parts) {
  const inPart = chapters.filter((c) => c.part === part && c.rows.length);
  if (!inPart.length) continue;
  cat += `\n## ${partTitles[part] || part}\n`;
  for (const c of inPart) {
    cat += `\n### [${c.title}](../${c.part}/${c.file})\n\n`;
    cat += '| ID | Practice | Applies to | Effort | First step |\n|---|---|---|---|---|\n';
    for (const r of c.rows) cat += `| ${r.slice(0, 5).join(' | ')} |\n`;
  }
}
writeFileSync(join(docs, 'reference', 'adoption-catalog.md'), cat);

// Resources
let res = `${note}\n# Resources\n\n`;
res += '> Every external link the chapters recommend, grouped by chapter. All are public. Tooling moves fast; if a link is dead, search for the name.\n';
const seen = new Set();
for (const part of parts) {
  const inPart = chapters.filter((c) => c.part === part && c.resources.length);
  if (!inPart.length) continue;
  res += `\n## ${partTitles[part] || part}\n`;
  for (const c of inPart) {
    const fresh = c.resources.filter((l) => {
      const url = (l.match(/\]\((https?:[^)\s]+)\)/) || [])[1];
      if (!url) return true;
      const key = url.replace(/\/$/, '');
      if (seen.has(key)) return false;
      seen.add(key);
      return true;
    });
    if (!fresh.length) continue;
    res += `\n### [${c.title}](../${c.part}/${c.file})\n\n${fresh.join('\n')}\n`;
  }
}
writeFileSync(join(docs, 'reference', 'resources.md'), res);

// FAQ index: docs/06-field-guides/04-faq.md is generated from docs/06-field-guides/faq/*.md
const faqDir = join(docs, '06-field-guides', 'faq');
const slug = (h) => h.trim().toLowerCase().replace(/[^\p{L}\p{N}\s_-]/gu, '').replace(/\s/g, '-');
let faq = `${note}\n# FAQ\n\n`;
faq += '> Short answers to the questions developers ask most when they start working with coding agents seriously, grouped by topic. Each answer ends with a pointer to the chapter that goes deeper. This page is the index; the answers are in the topic files.\n';
let faqCount = 0;
for (const file of readdirSync(faqDir).filter((f) => /^\d\d-.*\.md$/.test(f)).sort()) {
  const text = readFileSync(join(faqDir, file), 'utf8');
  const title = (text.match(/^# (?:FAQ: )?(.+)$/m) || [, file])[1].trim();
  const questions = [...text.matchAll(/^### (.+)$/gm)].map((m) => m[1].trim());
  const used = new Map();
  faq += `\n## [${title}](faq/${file})\n\n`;
  for (const q of questions) {
    let s = slug(q);
    const n = used.get(s) || 0;
    used.set(s, n + 1);
    if (n) s += `-${n}`;
    faq += `- [${q.replace(/[\[\]]/g, '')}](faq/${file}#${s})\n`;
    faqCount++;
  }
}
writeFileSync(join(docs, '06-field-guides', '04-faq.md'), faq);
console.log(`faq index: ${faqCount} questions`);

console.log(`catalogue: ${total} practices from ${chapters.length} chapters; resources: ${seen.size} unique links`);
for (const c of chapters) if (!c.rows.length) console.log(`  no "Adopt this" rows: ${c.part}/${c.file}`);
